import assert from 'node:assert/strict';
import { calculateFeeFlow, DEFAULT_FEE_FLOW } from '../../public/models/range-fee-flow-v2.js';
import { DEFAULT_WIDTHS, calculateWidthComparison } from '../../public/models/range-width.js';
import { widthFlowHash, widthFlowFromHash } from '../../public/lib/width-flow-links.js';
import { dragRangeToMax } from './touch-range.js';

export async function checkFeeFlow({ evaluate, click, fill, text, navigate, reload, base, call }) {
  const keys = ['teren-width-comparison-v1', 'teren-experiment-location-v1'];
  await navigate(base + 'liquidity.html#compare-widths');
  const saved = await evaluate(`${JSON.stringify(keys)}.map(key=>[key,localStorage.getItem(key)])`);
  const value = id => evaluate(`document.getElementById('${id}').value`);
  const state = () => evaluate("JSON.parse(localStorage.getItem('teren-width-comparison-v1'))");
  const openAssumptions = () => evaluate("document.getElementById('fee-flow-assumptions').open=true");
  try {
    await click('width-reset');
    await navigate(base + 'liquidity.html#follow-fees');
    assert.equal(await evaluate("document.getElementById('width-fee-view').hidden"), false);
    assert.equal(await evaluate("document.getElementById('width-principal-view').hidden"), true);
    assert.match(await text('fee-flow-mechanism'), /Only B is active/);
    assert.match(await text('fee-flow-count'), /No batches added/);
    await click('fee-flow-start');
    const capitalBefore = await value('fee-flow-competition');
    await fill('fee-flow-other-width', '20');
    assert.match(await text('fee-flow-quotes'), /0.50%/);
    await click('fee-flow-full-range');
    assert.match(await text('fee-flow-quotes'), /9.31%/);
    assert.equal(await value('fee-flow-competition'), capitalBefore);
    assert.equal(await evaluate("document.getElementById('fee-flow-other-width').disabled"), true);
    await click('fee-flow-full-range');
    await fill('fee-flow-other-width', '100');
    await evaluate("document.getElementById('width-inputs').open=true");
    await fill('width-price', '2400');
    await click('fee-flow-example');
    assert.equal(await evaluate('document.activeElement.id'), 'fee-flow-add');
    assert.equal((await state()).flow.batches.length, 2);
    const expectedState = (await state()).flow;
    const result = calculateFeeFlow(DEFAULT_WIDTHS, expectedState);
    assert.ok(result.ranges.every(range => range.netVsHolding < 0));
    const tokens = await evaluate("Array.from(document.querySelectorAll('#fee-flow-outcomes .width-token-key')).map(el=>el.textContent)");
    await evaluate("document.getElementById('width-inputs').open=true");
    await fill('width-price', '4000');
    assert.equal(await evaluate("document.getElementById('fee-flow-add').disabled"), true);
    assert.match(await text('fee-flow-error'), /no active LPs/);
    assert.equal(await evaluate("document.getElementById('fee-flow-source').hidden"), true);
    assert.equal((await state()).flow.batches.length, 2);
    await click('fee-flow-full-range');
    assert.match(await text('fee-flow-mechanism'), /Both ranges are outside/);
    assert.deepEqual(await evaluate("Array.from(document.querySelectorAll('#fee-flow-outcomes .width-token-key')).map(el=>el.textContent)"), tokens);
    await click('fee-flow-add');
    assert.equal((await state()).flow.batches.length, 3);
    assert.deepEqual(await evaluate("Array.from(document.querySelectorAll('#fee-flow-outcomes .width-token-key')).map(el=>el.textContent)"), tokens);
    await click('fee-flow-undo');
    await fill('width-price', '2400');
    await openAssumptions();
    await fill('fee-flow-volume', '0');
    assert.equal(await evaluate("document.getElementById('fee-flow-add').disabled"), true);
    await fill('fee-flow-volume', '123456.789');
    await fill('fee-flow-competition', '987654.321');
    const lastValid = await evaluate("localStorage.getItem('teren-width-comparison-v1')");
    const ledgerBefore = await text('fee-flow-batches');
    for (const [field, invalidValues, restored, message, summary] of [
      ['competition', ['', '0', '1000000000001'], '987654.321', 'Enter an amount from $1 to $1 trillion.', 'Check other LPs’ starting capital'],
      ['volume', ['', '-1', '1000000001'], '123456.789', 'Enter an amount from $0 to $1 billion.', 'Check trading volume'],
    ]) {
      for (const invalid of invalidValues) {
        await fill('fee-flow-' + field, invalid);
        assert.equal(await text('fee-flow-' + field + '-error'), message);
        assert.equal(await text('fee-flow-error'), '', 'The field error is not repeated by the model error.');
        assert.equal(await text('width-save-status'), '', 'An invalid edit does not claim it was saved.');
        assert.equal(await text('fee-flow-assumptions-summary'), summary);
        assert.equal(await text('fee-flow-competitor-capital'), field === 'competition' ? 'Check starting capital' : 'Next batch unavailable');
        assert.equal(await text('fee-flow-competitor-bounds'), '');
        assert.equal(await evaluate("document.getElementById('fee-flow-competitor-capital').hasAttribute('title')"), false);
        assert.equal(await evaluate("['fee-flow-quote','fee-flow-totals'].every(id=>document.getElementById(id).hidden)"), true);
        assert.equal(await evaluate("['fee-flow-add','fee-flow-example','width-share'].every(id=>document.getElementById(id).disabled)"), true);
        assert.equal(await evaluate("localStorage.getItem('teren-width-comparison-v1')"), lastValid, 'Invalid next-batch edits preserve the saved valid comparison.');
        assert.equal(await text('fee-flow-batches'), ledgerBefore, 'Already added batches remain visible while the next batch is invalid.');
        assert.equal(await text('fee-flow-ledger-count'), '(2)');
        await click('fee-flow-add');
        await click('width-share');
        assert.equal(await evaluate("document.getElementById('width-share-result').hidden"), true);
        assert.equal((await state()).flow.batches.length, 2);
        await fill('fee-flow-' + field, restored);
        assert.equal(await evaluate(`document.getElementById('fee-flow-${field}-error').hidden`), true);
        assert.equal(await evaluate("document.getElementById('width-share').disabled"), false);
      }
    }
    await fill('fee-flow-competition', '');
    await click('fee-flow-full-range');
    await fill('fee-flow-other-width', '40');
    assert.equal(await text('fee-flow-width-value'), '40.00% total width');
    assert.match(await text('width-bands-title'), /other LPs use 40\.00% width/);
    assert.equal(await evaluate("document.getElementById('fee-flow-other-width').getAttribute('aria-valuetext')"), '40.00% total width');
    await click('fee-flow-full-range');
    assert.equal(await text('fee-flow-width-value'), 'Full range');
    assert.match(await text('width-bands-title'), /other LPs use the full range/);
    assert.equal(await evaluate("document.getElementById('fee-flow-other-width').disabled"), true);
    assert.equal(await evaluate("localStorage.getItem('teren-width-comparison-v1')"), lastValid);
    await fill('fee-flow-competition', '987654.321');
    assert.match(await text('fee-flow-assumptions-summary'), /Trading \$123\.5K · other LPs \$987\.7K/);
    assert.equal(await evaluate("document.getElementById('fee-flow-totals').hidden"), false);
    assert.equal(await text('fee-flow-batches'), ledgerBefore);
    await fill('width-start', '');
    assert.equal(await text('fee-flow-assumptions-summary'), 'Check the shared starting setup');
    assert.equal(await evaluate("document.querySelectorAll('#fee-flow-batches li').length"), 2);
    assert.equal(await evaluate("localStorage.getItem('teren-width-comparison-v1')"), lastValid);
    await fill('width-start', '2000');
    assert.equal(await text('fee-flow-batches'), ledgerBefore);
    await click('width-share');
    const shared = await value('width-share-url');
    const parsed = widthFlowFromHash(new URL(shared).hash);
    assert.equal(parsed.flow.volume, 123456.789); assert.equal(parsed.flow.batches.length, 2);
    await reload();
    assert.equal(await value('fee-flow-volume'), '123456.789');
    assert.match(await text('fee-flow-count'), /2 of 8/);
    await navigate(base);
    assert.equal(await evaluate("document.getElementById('home-experiment').href"), shared);
    await navigate(shared);
    const beforeScene = await state();
    await click('width-fees-view');
    await evaluate("document.getElementById('fee-mechanics').open=true");
    await evaluate("document.querySelector('[data-fee-arbitrage-stage=\"1\"]').click()");
    assert.equal(await text('fee-arbitrage-market'), '$2,200.00');
    assert.equal(await text('fee-arbitrage-pool'), '$2,000.00');
    await evaluate("document.querySelector('[data-fee-arbitrage-stage=\"2\"]').click()");
    assert.equal(await text('fee-arbitrage-pool'), '$2,200.00');
    assert.match(await text('fee-arbitrage-eth'), /9.5346/);
    assert.match(await text('fee-arbitrage-usdc'), /20,976.18/);
    await evaluate("document.querySelector('[data-fee-arbitrage-stage=\"0\"]').click()");
    assert.match(await text('fee-arbitrage-eth'), /10 ETH/);
    assert.deepEqual((await state()).flow.batches, beforeScene.flow.batches);
    const calculated = calculateFeeFlow(parsed.inputs, parsed.flow);
    await evaluate("document.querySelector('[data-fee-apply=\"a\"]').click()");
    assert.equal(Number(await value('cl-fees')), calculated.ranges[0].feeValue);
    assert.equal(Number(await value('cl-lower')), calculated.ranges[0].lowerPrice);
    await navigate(shared);
    await click('width-balances-view');
    assert.equal(await evaluate("document.getElementById('width-principal-view').hidden"), false);
    assert.match(await text('width-holding'), /exclude fees/);
    await click('width-fees-view');
    assert.match(await text('fee-flow-count'), /2 of 8/);
    await evaluate("document.getElementById('width-inputs').open=true");
    const edge = calculateWidthComparison(DEFAULT_WIDTHS).ranges[0].upperPrice;
    await fill('width-price', String(edge));
    assert.equal(await evaluate("document.getElementById('fee-flow-add').disabled"), true);
    assert.match(await text('fee-flow-error'), /range edge/);
    assert.match(await text('fee-flow-count'), /2 of 8/);
    await fill('width-price', '2400');
    for (let i = 0; i < 6; i++) await click('fee-flow-add');
    assert.match(await text('fee-flow-count'), /8 of 8/);
    assert.equal(await evaluate("document.getElementById('fee-flow-add').disabled"), true);
    await click('fee-flow-clear');
    assert.match(await text('fee-flow-count'), /No batches added/);
    const malformed = shared.replace('flow=', 'bad=');
    await navigate(malformed); assert.match(await text('width-notice'), /default setup/);
    assert.equal(await evaluate("document.getElementById('width-fee-view').hidden"), true);
    console.log('PASS: fee allocation, retained tokens, preview separation, bounded ledger, edge protection, exact sharing, Home resume and handoffs');

    const mobileLink = widthFlowHash(DEFAULT_WIDTHS, { ...DEFAULT_FEE_FLOW, enabled: true });
    for (const width of [390, 320]) {
      await call('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: true });
      await navigate(base + 'liquidity.html' + mobileLink);
      await dragRangeToMax({ evaluate, call, fill }, 'width-price-slider');
      assert.match(await text('fee-flow-error'), /no active LPs/);
      assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'), true);
      assert.ok(await evaluate("['fee-flow-add','width-fees-view','width-balances-view'].every(id=>document.getElementById(id).getBoundingClientRect().height>=44)"));
      await click('fee-flow-start');
      await dragRangeToMax({ evaluate, call, fill }, 'fee-flow-other-width');
      assert.equal(await value('fee-flow-competition'), '1000000');
      assert.equal(await value('width-price'), '2000');
      await click('fee-flow-example');
      assert.equal(await evaluate('document.activeElement.id'), 'fee-flow-add');
      await openAssumptions();
      await fill('fee-flow-competition', '1000000000001');
      assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'), true);
      assert.equal(await text('fee-flow-competition-error'), 'Enter an amount from $1 to $1 trillion.');
      assert.equal(await text('fee-flow-error'), '');
      assert.equal(await evaluate("document.querySelectorAll('#fee-flow-batches li').length"), 2);
      const fields = await evaluate("['fee-flow-volume','fee-flow-competition'].map(id=>{const field=document.getElementById(id).parentElement,r=field.getBoundingClientRect();return {x:r.x,y:r.y,bottom:r.bottom,width:r.width,scroll:field.scrollWidth,client:field.clientWidth}})");
      assert.ok(Math.abs(fields[0].x - fields[1].x) < 1 && fields[1].y >= fields[0].bottom, 'Mobile next-batch fields stack in reading order.');
      assert.ok(fields.every(field => field.width > width * .6 && field.scroll <= field.client), 'Each field and its error fit a full-width mobile column.');
      await fill('fee-flow-competition', '1000000');
      const layout = await evaluate("Array.from(document.querySelectorAll('#fee-flow-outcomes article')).map(el=>({y:el.getBoundingClientRect().y,w:el.getBoundingClientRect().width}))");
      assert.ok(Math.abs(layout[0].y - layout[1].y) < 1 && layout.every(card => card.w > 110));
      await evaluate("document.getElementById('fee-mechanics').open=true");
      await evaluate("document.querySelector('[data-fee-arbitrage-stage=\"2\"]').click()");
      assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'), true);
      assert.ok(await evaluate("Array.from(document.querySelectorAll('[data-fee-arbitrage-stage]')).every(el=>el.getBoundingClientRect().height>=44)"));
      await click('nav-inspect');
      assert.equal(await evaluate("document.getElementById('width-workspace').hidden"), true);
      await navigate(base + 'liquidity.html#compare-widths');
      assert.equal(await evaluate("document.getElementById('width-fee-view').hidden"), false);
    }
    for (const width of [1280, 390, 320]) {
      await call('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: width < 750 });
      await navigate(base + 'liquidity.html#fee-mechanics');
      const mechanicsVisible = async () => {
        await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
        assert.equal(await evaluate("document.getElementById('width-fee-view').hidden"), false);
        assert.equal(await evaluate("document.getElementById('fee-mechanics').open"), true);
        const target = await evaluate("(()=>{const summary=document.querySelector('#fee-mechanics>summary'),rect=summary.getBoundingClientRect(),header=document.querySelector('.topbar').getBoundingClientRect();return {focused:document.activeElement===summary,top:rect.top,bottom:rect.bottom,header:header.bottom,height:innerHeight}})()");
        assert.equal(target.focused, true, 'The mechanics link focuses its opened disclosure.');
        assert.ok(target.top >= target.header + 8 && target.bottom < target.height, 'The requested illustration opens in view below the navigation.');
        assert.equal(await evaluate("[...document.querySelectorAll('.fee-scene-prices strong')].every(price=>price.scrollWidth<=price.clientWidth)"), true, 'Market and pool prices each fit their own column.');
      };
      await mechanicsVisible();
      // An unchanged same-page fragment still reopens and reaches its destination.
      await evaluate("document.getElementById('fee-mechanics').open=false;scrollTo(0,0);const link=document.createElement('a');link.href='#fee-mechanics';document.body.append(link);link.click();link.remove()");
      await mechanicsVisible();
    }
    console.log('PASS: fee-flow at 390px/320px, stable native price dragging, paired outcomes, focus and navigation');
  } finally {
    await evaluate(`${JSON.stringify(saved)}.forEach(([key,value])=>value===null?localStorage.removeItem(key):localStorage.setItem(key,value))`);
    await call('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
  }
}
